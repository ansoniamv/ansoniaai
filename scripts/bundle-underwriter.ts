// Pack anthropic/ (the underwriter agent, its environment and the
// full-underwrite skill) into supabase/functions/generate-model/underwriterBundle.ts,
// so generate-model's admin "setup" action can create or update them on
// Anthropic with the platform's own key. The key lives only in Supabase's
// function secrets, so nothing is created from a laptop.
//
//   deno run --allow-read --allow-write scripts/bundle-underwriter.ts
//
// Run it after any change under anthropic/ (sync-underwrite-skill.ts runs it
// for you), then redeploy generate-model and press "Set up" again.
import { parse as parseYaml } from "jsr:@std/yaml@1.0.5";

const ROOT = new URL("../anthropic/", import.meta.url);
const OUT = new URL("../supabase/functions/generate-model/underwriterBundle.ts", import.meta.url);
const SKILL_DIR = "skills/full-underwrite/";

const read = (p: string) => Deno.readTextFile(new URL(p, ROOT)).then((t) => t.replace(/\r\n/g, "\n"));

// ---- agent: YAML frontmatter is the config, the Markdown body the system prompt
const agentMd = await read("agents/underwriter.md");
const fm = agentMd.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
if (!fm) throw new Error("agents/underwriter.md has no frontmatter");
const { skills: _skills, ...agentConfig } = parseYaml(fm[1]) as Record<string, unknown>;
const agent = { ...agentConfig, system: fm[2].trim() };

const environment = parseYaml(await read("environments/underwriter.yaml")) as Record<string, unknown>;

// ---- skill: every file under the skill folder, uploaded as full-underwrite/<path>
const files: { path: string; content: string }[] = [];
async function walk(dir: string) {
  const entries = [...Deno.readDirSync(new URL(dir, ROOT))].sort((a, b) => a.name.localeCompare(b.name));
  for (const e of entries) {
    if (e.isDirectory) await walk(`${dir}${e.name}/`);
    else files.push({ path: `full-underwrite/${dir.slice(SKILL_DIR.length)}${e.name}`, content: await read(`${dir}${e.name}`) });
  }
}
await walk(SKILL_DIR);
if (!files.some((f) => f.path === "full-underwrite/SKILL.md")) throw new Error("no SKILL.md in the skill folder");

async function hash(v: unknown): Promise<string> {
  const bytes = new TextEncoder().encode(JSON.stringify(v));
  const d = new Uint8Array(await crypto.subtle.digest("SHA-256", bytes));
  return [...d].map((b) => b.toString(16).padStart(2, "0")).join("").slice(0, 16);
}

const bundle = {
  agent: { config: agent, hash: await hash(agent) },
  environment: { config: environment, hash: await hash(environment) },
  skill: { files, hash: await hash(files) },
};

await Deno.writeTextFile(
  OUT,
  "// Generated by scripts/bundle-underwriter.ts from anthropic/. Do not edit.\n" +
    "// deno-fmt-ignore-file\n" +
    `export const UNDERWRITER = ${JSON.stringify(bundle, null, 1)} as const;\n`,
);
console.log(
  `underwriterBundle.ts: agent ${bundle.agent.hash}, environment ${bundle.environment.hash}, ` +
    `skill ${bundle.skill.hash} (${files.length} files, ${files.reduce((n, f) => n + f.content.length, 0)} chars)`,
);
