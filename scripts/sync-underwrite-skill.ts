// Rebuild the platform's copy of the full-underwrite skill from the desktop one.
//
// The desktop skill is a single SKILL.md with its Python in appendices, written
// out to disk at the start of every run. The platform copy keeps the rules
// verbatim in UNDERWRITE.md and ships the appendix code as ready-made files in
// scripts/, so a run spends no tokens retyping 1,100 lines of Python. SKILL.md
// (the platform entry point, written by hand) is never touched here.
//
//   deno run --allow-read --allow-write --allow-net=jsr.io scripts/sync-underwrite-skill.ts <path to desktop SKILL.md>
//
// Run it whenever Chase changes the desktop skill, then redeploy generate-model
// and press "Set up" on a deal's model card (see anthropic/README.md).

const src = Deno.args[0];
if (!src) {
  console.error("usage: sync-underwrite-skill.ts <path to the desktop full-underwrite SKILL.md>");
  Deno.exit(1);
}
const OUT = new URL("../anthropic/skills/full-underwrite/", import.meta.url);

const text = (await Deno.readTextFile(src)).replace(/\r\n/g, "\n");
// Frontmatter off: the platform SKILL.md has its own.
const body = text.replace(/^---\n[\s\S]*?\n---\n+/, "");

// Appendix A (the coding exceptions) is data the rules refer to by name, so it
// stays in UNDERWRITE.md; it is also written out for load_exceptions().
const firstCode = body.search(/^## Appendix B:/m);
if (firstCode < 0) throw new Error("no '## Appendix B:' heading; has the skill's layout changed?");
const rules = body.slice(0, firstCode).trimEnd();
const exceptions = rules.match(/^## Appendix A:[^\n]*\n```\n([\s\S]*?)\n```/m)?.[1];
if (!exceptions) throw new Error("Appendix A has no code block of exceptions");

// "## Appendix X: name.py (...)" followed by a ```python block.
const scripts = [...body.slice(firstCode).matchAll(/^## Appendix [A-Z]+: (\w+\.py)[^\n]*\n```python\n([\s\S]*?)\n```/gm)];
if (scripts.length === 0) throw new Error("no appendix scripts found");

await Deno.mkdir(new URL("scripts/", OUT), { recursive: true });
await Deno.writeTextFile(
  new URL("UNDERWRITE.md", OUT),
  "<!-- Generated by scripts/sync-underwrite-skill.ts from the desktop full-underwrite skill. Do not edit here. -->\n\n" +
    rules + "\n",
);
await Deno.writeTextFile(new URL("scripts/exceptions.txt", OUT), exceptions + "\n");
for (const [, name, code] of scripts) {
  await Deno.writeTextFile(new URL(`scripts/${name}`, OUT), code + "\n");
}
console.log(`UNDERWRITE.md (${rules.split("\n").length} lines), exceptions.txt, ${scripts.map((m) => m[1]).join(", ")}`);

// Repack the function's copy so the next deploy carries the new skill.
await import("./bundle-underwriter.ts");
